"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { CalendarClock, ChevronRight, FileBarChart, RefreshCw, Sparkles } from "lucide-react";
import type { MonthlyReport } from "@/types";
import { useAppStore } from "@/store/app-store";
import { useCan, useScope } from "@/hooks/use-scope";
import { useInitialLoad } from "@/hooks/use-initial-load";
import { periodTotals } from "@/lib/analytics";
import { formatDate, formatDateTime, formatMonth, monthRange, previousMonth, today } from "@/lib/date";
import { formatMoney } from "@/lib/currency";
import { PageHeader } from "@/components/shared/page-header";
import { StatusBadge } from "@/components/shared/status-badge";
import { ConversionNote } from "@/components/shared/money";
import { EmptyState, TableSkeleton } from "@/components/shared/states";
import { DemoNotice } from "@/components/shared/demo-notice";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { cn } from "@/lib/utils";
import { GenerateReportDialog } from "./generate-report-dialog";
import { historyStartMonth } from "./report-data";

export function ReportsPage() {
  const loading = useInitialLoad();
  const reports = useAppStore((s) => s.reports);
  const transactions = useAppStore((s) => s.transactions);
  const { scope, money, branch } = useScope();
  const canGenerate = useCan("reports.generate");
  const [genOpen, setGenOpen] = useState(false);
  const [genMonth, setGenMonth] = useState<string | undefined>();

  const currentMonth = today().slice(0, 7);
  const lastClosed = previousMonth(currentMonth);
  const firstMonth = useMemo(() => historyStartMonth({ transactions }), [transactions]);

  const closedMonths = useMemo(() => {
    const out: string[] = [];
    for (let m = lastClosed; m >= firstMonth; m = previousMonth(m)) out.push(m);
    return out;
  }, [lastClosed, firstMonth]);

  const eligible = useMemo(() => closedMonths.filter((m) => {
    const r = reports.find((x) => x.month === m);
    return !r || r.status === "incomplete" || r.status === "failed";
  }), [closedMonths, reports]);

  const rows = useMemo(
    () =>
      closedMonths.map((m) => {
        const r = reports.find((x) => x.month === m);
        const range = monthRange(m);
        const totals = periodTotals(transactions, range.start, range.end, scope, money);
        return { month: m, report: r, totals };
      }),
    [closedMonths, reports, transactions, scope, money],
  );
  const anyConverted = rows.some((r) => r.totals.converted);
  const anyExcluded = rows.some((r) => r.totals.excludedForeign);

  const openGenerate = (m?: string) => {
    setGenMonth(m);
    setGenOpen(true);
  };

  return (
    <>
      <PageHeader
        title="Monthly Reports"
        description="Month-end summaries of revenue, expenses, profit, cash and outstanding balances, with AI-generated insights from your figures."
        actions={
          canGenerate && (
            <Button onClick={() => openGenerate()} disabled={eligible.length === 0}>
              <Sparkles /> Generate report
            </Button>
          )
        }
      />

      <div className="mb-4 grid gap-4 md:grid-cols-[1fr_auto]">
        <Card className="flex-row items-center gap-4 p-4">
          <span className="flex size-10 shrink-0 items-center justify-center rounded-lg bg-muted text-muted-foreground">
            <CalendarClock className="size-5" aria-hidden />
          </span>
          <div className="min-w-0">
            <p className="text-sm font-medium">{formatMonth(currentMonth)} — in progress</p>
            <p className="text-sm text-muted-foreground">
              Available after month close on {formatDate(monthRange(currentMonth).end)}. Until then, see month-to-date figures on the{" "}
              <Link href="/dashboard" className="font-medium text-primary hover:underline">dashboard</Link>.
            </p>
          </div>
        </Card>
        <DemoNotice variant="ai" className="self-stretch md:max-w-sm">
          Insights are generated by rules over your report figures (simulated AI). They are not accounting or tax advice.
        </DemoNotice>
      </div>

      <Card className="gap-0 py-0">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b px-4 py-3">
          <h2 className="text-sm font-semibold">Closed months</h2>
          <p className="text-xs text-muted-foreground">Headline figures for {branch ? branch.name : "all branches"} in {money.display}</p>
        </div>
        {loading ? (
          <TableSkeleton rows={6} cols={6} />
        ) : rows.length === 0 ? (
          <EmptyState icon={FileBarChart} title="No closed months yet" description="Reports become available once a full month of transactions has been recorded." />
        ) : (
          <div className="overflow-x-auto">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Month</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead>Generated</TableHead>
                  <TableHead className="text-right">Revenue</TableHead>
                  <TableHead className="text-right">Net profit</TableHead>
                  <TableHead className="text-right"><span className="sr-only">Actions</span></TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {rows.map(({ month, report, totals }) => (
                  <TableRow key={month}>
                    <TableCell className="font-medium">
                      {report && report.status !== "generating" ? (
                        <Link href={`/reports/${report.id}`} className="hover:text-primary hover:underline">{formatMonth(month)}</Link>
                      ) : (
                        formatMonth(month)
                      )}
                    </TableCell>
                    <TableCell><ReportStatus report={report} /></TableCell>
                    <TableCell className="text-muted-foreground tabular-nums">{report?.generatedAt && report.status !== "generating" ? formatDateTime(report.generatedAt) : "—"}</TableCell>
                    <TableCell className="text-right tabular-nums">{report ? `${totals.converted ? "≈" : ""}${formatMoney(totals.revenue.value, money.display)}` : "—"}</TableCell>
                    <TableCell className={cn("text-right tabular-nums", report && totals.net < 0 && "text-error-text")}>{report ? formatMoney(totals.net, money.display) : "—"}</TableCell>
                    <TableCell className="text-right">
                      <div className="flex justify-end gap-1">
                        {canGenerate && report && (report.status === "incomplete" || report.status === "failed") && (
                          <Button variant="ghost" size="sm" onClick={() => openGenerate(month)}>
                            <RefreshCw /> Regenerate
                          </Button>
                        )}
                        {canGenerate && !report && (
                          <Button variant="outline" size="sm" onClick={() => openGenerate(month)}>
                            <Sparkles /> Generate
                          </Button>
                        )}
                        {report && report.status !== "generating" && (
                          <Button variant="outline" size="sm" asChild>
                            <Link href={`/reports/${report.id}`} aria-label={`View ${formatMonth(month)} report`}>
                              View <ChevronRight />
                            </Link>
                          </Button>
                        )}
                      </div>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>
        )}
        <ConversionNote converted={anyConverted} excludedForeign={anyExcluded} rate={money.rate} currency={money.display} className="border-t px-4 py-3" />
      </Card>

      {canGenerate && <GenerateReportDialog open={genOpen} onOpenChange={setGenOpen} months={eligible} initialMonth={genMonth} />}
    </>
  );
}

export function ReportStatus({ report }: { report?: MonthlyReport }) {
  if (!report) return <span className="text-sm text-muted-foreground">Not generated</span>;
  if (report.status === "incomplete") return <StatusBadge status="incomplete" label={`Incomplete · ${report.missing.length} item${report.missing.length === 1 ? "" : "s"}`} />;
  return <StatusBadge status={report.status} />;
}
